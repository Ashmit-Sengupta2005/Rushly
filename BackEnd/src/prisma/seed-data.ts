// Demo catalog for `prisma db seed`. Kept apart from seed.ts so the seeding
// logic stays readable. Images are Unsplash photo ids (checked by eye — the
// names describe what's actually in the photo).

export interface CategorySeed {
  slug: string;
  name: string;
  description: string;
}

export interface ProductSeed {
  slug: string;
  name: string;
  description: string;
  price: number; // paise
  stock: number;
  categorySlug: string;
  images: string[]; // Unsplash photo ids
  isDropExclusive?: boolean; // only buyable while its category's event is live
}

export interface EventSeed {
  slug: string;
  title: string;
  tagline: string;
  categorySlug: string;
  image: string; // Unsplash photo id
  daysOfWeek: number[]; // IST, 0 = Sunday; [] = daily
  startTime: string; // "HH:MM" IST
  durationMinutes: number;
}

